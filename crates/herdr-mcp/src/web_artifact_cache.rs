//! Bounded, short-lived local cache for ChatGPT Web generated-image artifacts.
//!
//! This is the Rust-side landing point of the authenticated byte bridge. The
//! browser extension captures image bytes in the ChatGPT page context and sends
//! them (never a token/cookie/download URL) as a dedicated native-host message;
//! this module stores them in a secure, short-lived, stateless disk cache under
//! the config directory (no shared-memory registry, no schema bump). Web agents
//! reach the cache through the internal `artifact.*` local dispatch, and
//! non-sensitive metadata is exposed through `herdr_inspect` workstation info.
//!
//! Security posture:
//! * directory `0700`, entries `0600`, symlinked cache dirs/entries rejected;
//! * raw payloads are image-only (PNG/JPEG/GIF/WebP) with magic validation;
//! * SHA-256 recomputed in Rust; a browser-supplied digest must match;
//! * conversation/file IDs are validated to a strict, path-safe shape;
//! * deduplicated by `(conversation_id, file_id)` within a short TTL;
//! * bounded artifact count and total bytes under the config dir.

use crate::artifact_import;
use serde_json::{Map, Value, json};
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;

pub const RAW_LIMIT_BYTES: usize = 8 * 1024 * 1024;
pub const TTL_SECS: u64 = 15 * 60;
pub const MAX_ARTIFACTS: usize = 32;
pub const MAX_TOTAL_BYTES: usize = 64 * 1024 * 1024;
pub const CACHE_DIR_NAME: &str = "web-artifacts";
const META_SCHEMA: u32 = 1;
const MIN_FILE_ID_LEN: usize = 4;
const MAX_FILE_ID_LEN: usize = 256;
const MAX_CONVERSATION_ID_LEN: usize = 128;

/// Artifact IDs are generated by this runtime as 32 lowercase hex characters.
/// Metadata carrying any other shape is corrupt and must fail closed (it is
/// never a path component, but the strict check keeps every consumer honest).
pub fn validate_artifact_id(value: &str) -> Result<(), String> {
    let valid = value.len() == 32
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte));
    if valid {
        Ok(())
    } else {
        Err("artifact_id must be 32 lowercase hex characters".to_owned())
    }
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CapturedArtifact {
    pub artifact_id: String,
    pub conversation_id: String,
    pub file_id: String,
    pub mime: String,
    pub bytes: usize,
    pub sha256: String,
    pub captured_at: u64,
    pub expires_at: u64,
}

impl CapturedArtifact {
    pub fn metadata_json(&self) -> Value {
        json!({
            "artifact_id": self.artifact_id,
            "conversation_id": self.conversation_id,
            "file_id": self.file_id,
            "mime": self.mime,
            "bytes": self.bytes,
            "sha256": self.sha256,
            "captured_at": self.captured_at,
            "expires_at": self.expires_at,
        })
    }
}

