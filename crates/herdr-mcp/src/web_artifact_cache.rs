    // Each png entry is 5 bytes; MAX_ARTIFACTS is 32 and MAX_TOTAL_BYTES is huge
    // relative to these, so the count bound dominates and eviction must drop
    // the oldest entries while keeping the newest.
    #[test]
    fn eviction_drops_oldest_not_newest_on_count_overflow() {
        let config = temp_config();
        let png = png_bytes();
        let mut captured = Vec::new();
        for index in 0..(MAX_ARTIFACTS + 4) {
            let entry = capture(
                &config,
                &format!("conv-{index}"),
                &format!("file-{index}"),
                "image/png",
                &png,
                None,
            )
            .unwrap();
            captured.push(entry);
        }
        let listed = list(&config).unwrap();
        assert_eq!(listed.len(), MAX_ARTIFACTS, "count bound is enforced");
        // Newest MAX_ARTIFACTS survive; the first 4 (oldest) are evicted.
        let present_ids = listed
            .iter()
            .map(|value| value["artifact_id"].as_str().unwrap().to_owned())
            .collect::<Vec<_>>();
        for entry in captured.iter().take(4) {
            assert!(
                !present_ids.contains(&entry.artifact_id),
                "oldest entry {} must be evicted first",
                entry.artifact_id
            );
        }
        for entry in captured.iter().skip(4) {
            assert!(
                present_ids.contains(&entry.artifact_id),
                "newest entry {} must survive",
                entry.artifact_id
            );
        }
        fs::remove_dir_all(&config).unwrap();
    }

    #[test]
    fn eviction_enforces_total_byte_bound() {
        let config = temp_config();
        // Each entry 3 MiB so the 64 MiB byte cap binds well before the 32-entry
        // count cap (32 x 3 MiB = 96 MiB > 64 MiB), proving the byte budget.
        let mut big = Vec::with_capacity(3 * 1024 * 1024);
        big.extend_from_slice(b"\x89PNG\r\n\x1a\n");
        big.resize(3 * 1024 * 1024, 0);
        for index in 0..40 {
            capture(
                &config,
                &format!("conv-big-{index}"),
                &format!("file-big-{index}"),
                "image/png",
                &big,
                None,
            )
            .unwrap();
        }
        let listed = list(&config).unwrap();
        let total_bytes = listed
            .iter()
            .map(|value| value["bytes"].as_u64().unwrap_or(0))
            .sum::<u64>();
        assert!(total_bytes <= MAX_TOTAL_BYTES as u64, "byte bound enforced");
        // With 3 MiB entries, ~21 fit under 64 MiB, so the count is well below
        // the 32-entry cap — proving byte eviction (not just count) drove this.
        assert!(listed.len() < MAX_ARTIFACTS);
        assert!(!listed.is_empty());
        fs::remove_dir_all(&config).unwrap();
    }

    #[test]
    fn tampered_metadata_fails_closed() {
        let config = temp_config();
        let png = png_bytes();
        let valid = capture(&config, "conv-1", "file-tamper-1", "image/png", &png, None).unwrap();
        let dir = cache_dir_if_present(&config).unwrap().unwrap();
        let (_, meta_path) = entry_paths(&dir, &valid.artifact_id);

        // Corrupt artifact_id (not 32 lowercase hex) must be ignored.
        let bad_id = "../etc/passwd";
        let mut tampered = valid.metadata_json();
        tampered["artifact_id"] = json!(bad_id);
        tampered["schema"] = json!(META_SCHEMA);
        fs::write(&meta_path, serde_json::to_vec(&tampered).unwrap()).unwrap();
        assert!(fs::read_to_string(&meta_path).unwrap().contains(bad_id));
        assert_ne!(
            list(&config).unwrap().len(),
            1,
            "corrupt schema-free meta is dropped"
        );
        // read() with the corrupted (non-hex) id must fail closed, not traverse.
        assert_eq!(read(&config, bad_id).unwrap_err(), "artifact_not_found");

        // Re-seed a valid entry, then tamper the MIME to a non-image type.
        let valid2 = capture(&config, "conv-1", "file-tamper-2", "image/png", &png, None).unwrap();
        let (_, meta2) = entry_paths(&dir, &valid2.artifact_id);
        let mut mime_tamper = valid2.metadata_json();
        mime_tamper["mime"] = json!("text/plain");
        mime_tamper["schema"] = json!(META_SCHEMA);
        fs::write(&meta2, serde_json::to_vec(&mime_tamper).unwrap()).unwrap();
        assert!(
            list(&config)
                .unwrap()
                .iter()
                .all(|value| value["artifact_id"] != valid2.artifact_id),
            "non-image mime metadata must be dropped"
        );
        assert!(read(&config, &valid2.artifact_id).is_err());

        fs::remove_dir_all(&config).unwrap();
    }

