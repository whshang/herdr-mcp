// Validation
// ---------------------------------------------------------------------------

/// ChatGPT conversation IDs are opaque base64url-ish identifiers from `/c/<id>`.
/// Accept only path-safe tokens: no separators, whitespace, or control bytes.
pub fn validate_conversation_id(value: &str) -> Result<(), String> {
    if value.is_empty() || value.len() > MAX_CONVERSATION_ID_LEN || !value.bytes().all(is_id_byte) {
        return Err("artifact conversation_id has an invalid shape".to_owned());
    }
    Ok(())
}

/// ChatGPT `sediment://file_<id>` file identifiers. Same path-safe token rules;
/// the download route appends the id to a URL path, so traversal bytes (`/`,
/// `\`, NUL) and reserved delimiters are structurally impossible.
pub fn validate_file_id(value: &str) -> Result<(), String> {
    if value.len() < MIN_FILE_ID_LEN
        || value.len() > MAX_FILE_ID_LEN
        || !value.bytes().all(is_id_byte)
    {
        return Err("artifact file_id has an invalid shape".to_owned());
    }
    Ok(())
}

fn is_id_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.' | b':' | b'=' | b'+')
}

pub fn validate_sha256(value: &str) -> Result<(), String> {
    if value.len() == 64 && value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        Ok(())
    } else {
        Err("artifact SHA-256 must be 64 hexadecimal characters".to_owned())
    }
}

pub fn image_only_mime(value: &str) -> Result<&'static str, String> {
    let mime = artifact_import::supported_mime(value)
        .ok_or_else(|| format!("unsupported artifact MIME type '{value}'"))?;
    if !artifact_import::is_image_mime(mime) {
        return Err(format!("artifact MIME type '{mime}' is not an image"));
    }
    Ok(mime)
}

