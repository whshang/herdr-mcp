#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(repoRoot, "relay/deno/server.ts");
const outputPath = path.join(
  repoRoot,
  "supabase/functions/herdr-relay/index.ts",
);
const entrypointMarker = "// Entrypoint for `deno run` or Deno Deploy";

export function buildSupabaseRelaySource(source) {
  const markerIndex = source.indexOf(entrypointMarker);
  if (markerIndex < 0) {
    throw new Error(`missing Relay entrypoint marker: ${entrypointMarker}`);
  }

  const sharedSource = source.slice(0, markerIndex).trimEnd();
  return `${sharedSource}\n\n// GENERATED Supabase Edge Function entrypoint.\n// Source of truth: relay/deno/server.ts. Do not edit this file by hand.\nconst edgeRuntime = (globalThis as typeof globalThis & {\n  EdgeRuntime?: { waitUntil(promise: Promise<unknown>): void };\n}).EdgeRuntime;\n\nDeno.serve((request: Request) =>\n  handleRequest(request, {\n    pathPrefix: \"/herdr-relay\",\n    waitUntil: edgeRuntime?.waitUntil.bind(edgeRuntime),\n  })\n);\n`;
}

export function expectedSupabaseRelaySource() {
  return buildSupabaseRelaySource(fs.readFileSync(sourcePath, "utf8"));
}

function main() {
  const expected = expectedSupabaseRelaySource();
  const check = process.argv.includes("--check");
  if (check) {
    const actual = fs.existsSync(outputPath)
      ? fs.readFileSync(outputPath, "utf8")
      : "";
    if (actual !== expected) {
      console.error(
        "supabase/functions/herdr-relay/index.ts is stale; run npm run relay:supabase:bundle",
      );
      process.exitCode = 1;
    }
    return;
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
